#!/usr/bin/env bash
# Sean's own fonts on every device (2026-11-08).
#
# Why: Appearance → Text/Interface/Monospace font names fonts installed only on the Mac
# (~/Library/Fonts). Obsidian Sync copies the NAMES to the iPhone, not the files, and
# Obsidian on iOS cannot use fonts installed elsewhere on the phone — so every font showed
# "not installed". Fix: embed the three fonts that are actually used (first in each list)
# as a CSS snippet inside the vault; Sync carries the snippet to every device.
#
# Licensing: Berkeley Mono is a personal commercial licence — the output goes ONLY into
# Sean's private vault, never into the theme repo or theme.css. Nothing here is committed
# except this script.
#
# Usage: scripts/personal-fonts.sh "<vault>"   (writes .obsidian/snippets/enough-light-sean-fonts.css)
set -euo pipefail
VAULT=${1:?usage: personal-fonts.sh <vault>}
F="$HOME/Library/Fonts"
OUT="$VAULT/.obsidian/snippets/enough-light-sean-fonts.css"
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
# Latin + punctuation + arrows + box drawing (enough for notes, UI and code; drops Nerd icons).
UNICODES="U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2190-21FF,U+2212,U+2215,U+2500-257F,U+25A0-25FF,U+2713-2717,U+FEFF,U+FFFD"
FT="uvx --quiet --with brotli --from fonttools"

woff2() { # src out [font-number]
  $FT pyftsubset "$1" ${3:+--font-number=$3} --unicodes="$UNICODES" --flavor=woff2 \
    --layout-features='*' --output-file="$2"
}
face() { # family weight style woff2 [local-name]
  # local() first: the Mac keeps using its installed copy; other devices use the embedded one.
  printf '@font-face{font-family:"%s";font-weight:%s;font-style:%s;font-display:swap;src:local("%s"),url(data:font/woff2;base64,%s) format("woff2");}\n' \
    "$1" "$2" "$3" "${5:-$1}" "$(base64 < "$4" | tr -d '\n')"
}

woff2 "$F/Berkeley Mono Variable.otf"            "$TMP/berk.woff2"
woff2 "$F/Iosevka-Regular.ttc"                   "$TMP/ios-400.woff2" 0
woff2 "$F/Iosevka-Bold.ttc"                      "$TMP/ios-700.woff2" 0
woff2 "$F/FantasqueSansMNerdFontMono-Regular.ttf" "$TMP/fan-400.woff2"
woff2 "$F/FantasqueSansMNerdFontMono-Bold.ttf"    "$TMP/fan-700.woff2"

{
  echo "/* Enough Light — Sean's fonts, embedded so they work on iPhone/iPad too."
  echo "   Generated by obsidian-enough-light/scripts/personal-fonts.sh on $(date +%F). Do not edit by hand. */"
  face "Berkeley Mono Variable" "100 900" normal "$TMP/berk.woff2"
  face "Iosevka" 400 normal "$TMP/ios-400.woff2" "Iosevka"
  face "Iosevka" 700 normal "$TMP/ios-700.woff2" "Iosevka Bold"
  face "FantasqueSansM Nerd Font Mono" 400 normal "$TMP/fan-400.woff2"
  face "FantasqueSansM Nerd Font Mono" 700 normal "$TMP/fan-700.woff2" "FantasqueSansM Nerd Font Mono Bold"
} > "$OUT"
ls -la "$OUT" | awk '{print $5" bytes → "$NF}'
